"""Emit synthetic-GL definitions for the entry points sl_gfx_dl.c calls directly.

Reads the installed GL/gl.h prototypes and reuses each parameter list VERBATIM,
so the generated definition carries the header's own types and names. The
fixture still includes the real GL/gl.h, so a signature that disagreed with the
header would stop the build rather than mislink - which is what makes a
generated file safe to trust here.

Every definition is non-static and carries the entry point's own name, because
sl_gfx_dl.c calls these directly rather than through a resolver: with
-D_GDI32_ the header's dllimport decoration is empty, so the call resolves to
whatever definition the link provides, and this file is it.
"""
import re
import sys

GL_H = r"C:\msys64\mingw32\include\GL\gl.h"
NEEDED = sys.argv[1]
OUT = sys.argv[2]

# Entry points with a hand-written recording body in sl_gfx_seamgl.c: the
# generator must not emit a second definition of any of them.
RECORDED = {
    "glEnable", "glDisable", "glVertexPointer", "glDrawArrays", "glDrawElements",
    "glColorPointer", "glTexCoordPointer", "glNormalPointer",
    "glEnableClientState", "glDisableClientState", "glGetString", "glGetError",
    "glGetIntegerv", "glGetFloatv", "glIsEnabled",
}

with open(NEEDED, "r", encoding="utf-8") as fh:
    wanted = [ln.strip() for ln in fh if ln.strip()]

src = open(GL_H, "r", encoding="utf-8", errors="replace").read()

# `const GLubyte *APIENTRY glGetString(...)` attaches the star straight to
# APIENTRY, so the separator before it is optional rather than whitespace.
proto = re.compile(
    r"WINGDIAPI\s+(.+?)\s*APIENTRY\s+(gl\w+)\s*\(([^;]*?)\)\s*;",
    re.S,
)
protos = {}
for m in proto.finditer(src):
    protos[m.group(2)] = (m.group(1).strip(), " ".join(m.group(3).split()))

missing = [n for n in wanted if n not in protos]
if missing:
    print("NO PROTOTYPE FOUND for: %s" % ", ".join(missing))
    sys.exit(2)


def ident(param):
    """The declared parameter's identifier, or None for a bare type."""
    m = re.search(r"(\w+)\s*(\[\s*\d*\s*\])?$", param)
    if m is None:
        return None
    name = m.group(1)
    # A trailing word that is only a type keyword is not a parameter name.
    if re.fullmatch(r"(void|GL\w+|const|unsigned|int|float|double|char|short)",
                    name):
        return None
    return name


lines, emitted, skipped = [], [], []
for name in wanted:
    if name in RECORDED:
        skipped.append(name)
        continue
    ret, args = protos[name]
    if args in ("void", ""):
        plist, names = "void", []
    else:
        parts = [p.strip() for p in args.split(",")]
        names = [ident(p) for p in parts]
        plist = ", ".join(
            p if names[i] else "%s unused%d" % (p, i) for i, p in enumerate(parts))
        names = [n if n else "unused%d" % i for i, n in enumerate(names)]
    body = ["%s APIENTRY %s(%s)" % (ret, name, plist), "{", "    seam_enter();"]
    for nm in names:
        body.append("    (void) %s;" % nm)
    if ret != "void":
        body.append("    return (%s) 0;" % ret)
    body.append("}")
    lines.append("\n".join(body))
    emitted.append(name)

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* GENERATED by tools/profiling/native/genseamstubs.py - do not "
             "edit by hand.\n"
             " *\n"
             " * One inert definition per GL 1.1 entry point sl_gfx_dl.c calls and this\n"
             " * fixture does not need to observe. Each counts the call and discards its\n"
             " * arguments. The parameter lists come from the installed GL/gl.h, which the\n"
             " * fixture still includes, so a signature that disagreed would stop the build.\n"
             " *\n"
             " * The entry points the fixture DOES observe are hand-written in\n"
             " * sl_gfx_seamgl.c and are deliberately absent here. */\n\n")
    fh.write("\n\n".join(lines))
    fh.write("\n")

print("emitted %d inert definitions" % len(emitted))
print("hand-written elsewhere, skipped: %s" % ", ".join(skipped))
